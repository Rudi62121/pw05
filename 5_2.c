// Тип фигуры / Паттерн: Диагональная матрица (главная диагональ)
// Заполняющий символ: x
// Высота фигуры HEIGHT = 5
//
// ПОЯСНЕНИЕ К ЗАДАНИЮ:
// Внешний цикл управляет индексом строки `i` от 0 до HEIGHT-1. Внутренний цикл
// управляет индексом столбца `j` от 0 до HEIGHT-1. Для формирования главной 
// диагонали символ 'x' выводится в позиции, где номер строки совпадает с номером 
// столбца (i == j). В остальных позициях выводятся пробелы. Таким образом, 
// счетчики внутренних циклов последовательно проверяют координаты каждой точки
// экрана и определяют, нужно ли печатать заполняющий символ.
// ============================================================================

#include <stdio.h>

#define HEIGHT 5

int main(void) {
    for (int i = 0; i < HEIGHT; i++) {
        for (int j = 0; j < HEIGHT; j++) {
            if (i == j) {
                printf("x");
            } else {
                printf(" ");
            }
        }
        printf("\n");
    }
    return 0;
}
