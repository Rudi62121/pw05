// Формула члена ряда f(i): sin(i) / i
// Пример вывода для N = 5: SUM: 1.072296
//
// ПОЯСНЕНИЕ К ЗАДАНИЮ:
// Переменную-аккумулятор необходимо инициализировать вещественным нулем (0.0),
// так как в языке C тип константы определяет тип выполняемой операции. При 
// использовании целого нуля (0) без явного указания типа может произойти 
// неявное приведение типов или логическая ошибка интерпретации контекста в 
// сложных выражениях. Инициализация в виде `double sum = 0.0;` явно задает 
// тип double для ячейки памяти и предотвращает потенциальную потерю точности 
// на самом первом шаге сложения с вещественным членом ряда f(i).
// ============================================================================

#include <stdio.h>
#include <math.h>

int main(void) {
    int N;

    while (1) {
        printf("Введите количество слагаемых N (N <= 0 для выхода): ");
        if (scanf("%d", &N) != 1) {
            printf("Ошибка ввода.\n");
            break;
        }

        if (N <= 0) {
            break;
        }

        double sum = 0.0;
        for (int i = 1; i <= N; i++) {
            double term = sin((double)i) / (double)i;
            sum += term;
        }

        printf("SUM: %.6f\n", sum);
    }

    return 0;
}
