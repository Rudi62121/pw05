// Формула функции calc(a, b): (a + b)^3 / (a^2 + b^2)
// Физический смысл: Пиковая нагрузка
// Пример вывода для a=4.0, b=2.0: 10.8000
//
// ПОЯСНЕНИЕ К ЗАДАНИЮ:
// Функция объявлена с типом `double`, а не `float`, для обеспечения более 
// высокой точности вычислений (64 бита против 32 бит). Это снижает риск потери 
// точности при возведении чисел в куб и делении вещественных величин. 
// Ключевое слово `return` вычисляет выражение, стоящее после него, помещает 
// результат в специальный регистр процессора (или стек) для возвращаемых значений,
// мгновенно завершает выполнение текущей функции и передает управление обратно 
// в точку вызова внутри функции `main()`, где сохраненное значение может быть 
// сразу же использовано.
// ============================================================================

#include <stdio.h>

double calc(double a, double b) {
    double numerator = (a + b) * (a + b) * (a + b);
    double denominator = (a * a) + (b * b);
    
    // Защита от деления на ноль
    if (denominator == 0.0) {
        return 0.0; 
    }
    
    return numerator / denominator;
}

int main(void) {
    double a, b;

    printf("Введите пары чисел a и b (любой некорректный символ для выхода):\n");
    while (scanf("%lf %lf", &a, &b) == 2) {
        double result = calc(a, b);
        printf("Result: %.4f\n", result);
    }

    return 0;
}
