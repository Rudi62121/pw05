// ЗАДАНИЕ 5.1. ВАРИАНТ 4
// Физический смысл / Формула Y = f(X): 1 / X
// Начальное значение A = 1.0, Конечное значение B = 5.0, Шаг H = 0.5
//
// ПОЯСНЕНИЕ К ЗАДАНИЮ:
// Вещественные числа (типа float/double) хранятся в памяти компьютера в
// двоичной системе счисления с фиксированным количеством бит для мантиссы.
// Дробные значения, такие как 0.5, в данном случае представимы точно (поскольку
// являются степенью двойки: 2^-1), однако в общем случае шаги (например, 0.1) 
// невозможно представить в двоичной системе абсолютно точно, что приводит к 
// бесконечной периодической двоичной дроби. При многократном сложении (X += H) 
// в цикле погрешность округления накапливается на каждой итерации. Это приводит 
// к тому, что конечное значение X может оказаться чуть больше или чуть меньше B 
// (например, 5.000000000001 или 4.999999999999). Из-за этого условие X <= B 
// может либо сработать лишний раз, либо завершить цикл раньше, не выполнив 
// последнюю итерацию в конечной точке.
// ============================================================================

#include <stdio.h>

int main(void) {
    double A = 1.0;
    double B = 5.0;
    double H = 0.5;
    int iteration = 1;

    printf("Итерация |    X     |    Y     \n");
    printf("-------------------------------\n");

    for (double x = A; x <= B; x += H) {
        double y = 1.0 / x;
        printf("%8d | %8.4f | %8.4f\n", iteration, x, y);
        iteration++;
    }

    return 0;
}
