// Правило заполнения массива: Треугольные числа (первые 8)
// Требуемая операция обработки: Вывести в обратном порядке
//
// ПОЯСНЕНИЕ К ЗАДАНИЮ:
// Индексация в C начинается с нуля, потому что имя массива фактически является 
// указателем на его самый первый элемент. Индекс в квадратных скобках `arr[i]` 
// обозначает смещение (offset) относительно начального адреса в памяти. 
// Запись `arr[i]` эквивалентна выражению `*(arr + i)`. Таким образом, первый 
// элемент имеет смещение 0 (`*(arr + 0)`), что делает обращение к памяти 
// максимально быстрым, исключая лишнюю операцию вычитания единицы при каждом 
// обращении, которая требовалась бы при индексации с 1.
// ============================================================================

#include <stdio.h>

int main(void) {
    double arr[8];

    // Заполнение массива треугольными числами: T_n = n * (n + 1) / 2
    // Для индексов i от 0 до 7, порядковый номер n = i + 1
    for (int i = 0; i < 8; i++) {
        double n = (double)(i + 1);
        arr[i] = (n * (n + 1)) / 2.0;
    }

    // Вывод исходного массива
    for (int i = 0; i < 8; i++) {
        printf("%.2f ", arr[i]);
    }
    printf("\n");

    // Вывод обработанного массива (в обратном порядке)
    for (int i = 7; i >= 0; i--) {
        printf("%.2f ", arr[i]);
    }
    printf("\n");

    return 0;
}
